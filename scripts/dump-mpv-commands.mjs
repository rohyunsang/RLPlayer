#!/usr/bin/env node
/**
 * The pinned mpv binary's own command list, captured so the ownership table can
 * be checked against it instead of against somebody's memory.
 *
 * `src/main/core/mpv/ownership.ts` carries a COMMAND → PROPERTIES-IT-WRITES
 * table. That table has to be hand-written — `--input-cmdlist` prints argument
 * SIGNATURES, not side effects, and no binary can tell you that `frame-step`
 * writes `pause`. What it CAN tell you is which command names exist, and that
 * is where the previous version went wrong: `seek`, `frame-step`,
 * `frame-back-step`, `revert-seek` and `sub-seek` had no owner at all, so
 * `assertCommand('nav-chapters', 'seek', strict)` returned true and M25 could
 * seek through a command §3.6 says it does not own.
 *
 * So: this writes the names to `docs/parity/mpv-commands.json`, and
 * `src/main/core/mpv/commands.test.ts` fails if the side-effect table names a
 * command the binary does not have, if a command with a side effect has no
 * owner, or if a module claims a command that does not exist.
 *
 * Run:  node scripts/dump-mpv-commands.mjs
 * Re-run it whenever `scripts/fetch-mpv.mjs` pins a new build.
 */
import { execFileSync } from 'node:child_process'
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const repo = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const exe = path.join(repo, 'resources', 'mpv', 'mpv.exe')
const out = path.join(repo, 'docs', 'parity', 'mpv-commands.json')

if (!fs.existsSync(exe)) {
  console.error(`mpv not found at ${exe}. Run "npm run fetch:mpv" first.`)
  process.exit(1)
}

const version = execFileSync(exe, ['--version'], { encoding: 'utf8' }).split('\n')[0].trim()

/**
 * `--input-cmdlist` prints `name  arg=Type [opt=Type]`, one per line, with the
 * name in the first whitespace-delimited column.
 */
const commands = execFileSync(exe, ['--input-cmdlist'], { encoding: 'utf8', maxBuffer: 4 << 20 })
  .split(/\r?\n/)
  .map((line) => line.trim().split(/\s+/)[0])
  .filter((name) => name && /^[a-z][a-z0-9_-]*$/.test(name))
  .sort()

if (commands.length < 50) {
  console.error(`only ${commands.length} commands parsed; --input-cmdlist output looks wrong`)
  process.exit(1)
}

fs.writeFileSync(
  out,
  JSON.stringify(
    {
      note:
        'Generated by scripts/dump-mpv-commands.mjs from the pinned mpv binary. ' +
        'Do not hand-edit: re-run the script when the pin changes.',
      version,
      commands
    },
    null,
    2
  ) + '\n'
)
console.log(`wrote ${commands.length} commands from ${version} to docs/parity/mpv-commands.json`)
